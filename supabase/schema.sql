create table if not exists public.cars (
  id          bigint generated by default as identity primary key,
  slug        text not null unique,
  name        text not null,
  year        int  not null,
  engine      text not null,
  km          int  not null default 0,
  country     text not null,
  price       text not null default 'Su richiesta',
  status      text not null default 'Disponibile',
  description text not null default ''
);

create table if not exists public.car_photos (
  id     bigint generated by default as identity primary key,
  car_id bigint not null references public.cars(id) on delete cascade,
  url    text not null,
  sort   int  not null default 0
);

create index if not exists car_photos_car_id_idx on public.car_photos(car_id);

-- Lettura pubblica; scrittura solo da dashboard / service_role (nessuna policy di insert/update/delete).
alter table public.cars enable row level security;
alter table public.car_photos enable row level security;

drop policy if exists "cars public read" on public.cars;
create policy "cars public read" on public.cars for select to anon, authenticated using (true);

drop policy if exists "car_photos public read" on public.car_photos;
create policy "car_photos public read" on public.car_photos for select to anon, authenticated using (true);
